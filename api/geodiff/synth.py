"""Deterministic synthetic inventories for the fictional Cedar Hollow Parks Department.

All data produced here is SYNTHETIC. The street grid sits near Dallas, Texas only to give
realistic latitudes; streets, parks and assets are invented and do not describe any real
city inventory.

The generator injects changes into a proposed version and writes an *independent* change
manifest as it goes. The manifest is built from the generator's own intent (which asset it
moved, how far, which field it edited) and never calls the comparison engine, so tests can
check the engine against it.
"""

from __future__ import annotations

import copy
import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from geodiff.engine.geodesy import offset

SEED = 20261118
TOLERANCE_M = 2.0
COORD_DECIMALS = 8  # ~1 mm; keeps near-threshold cases 1 cm clear of rounding effects
DEPARTMENT = "Cedar Hollow Parks Department (fictional)"
SYNTHETIC_NOTE = (
    "SYNTHETIC DATA generated by GeoDiff for demonstration. Not a real city inventory; "
    "changes are injected by a seeded generator, not reported by any agency."
)

# Street grid near Dallas, TX. Blocks are ~187 m (E-W) x ~122 m (N-S).
LON0, LAT0 = -96.8120, 32.7740
DLON, DLAT = 0.0020, 0.0011
COLS, ROWS = 20, 24
NS_STREETS = [
    "Pecan",
    "Redbud",
    "Mesquite",
    "Sycamore",
    "Juniper",
    "Bois d'Arc",
    "Cedar",
    "Willow",
    "Hackberry",
    "Magnolia",
    "Cypress",
    "Laurel",
    "Persimmon",
    "Chinaberry",
    "Live Oak",
    "Yaupon",
    "Catalpa",
    "Buckeye",
    "Walnut",
    "Hawthorn",
    "Sumac",
]
EW_STREETS = [
    f"{n}{'st' if n % 10 == 1 and n != 11 else 'nd' if n % 10 == 2 and n != 12 else 'rd' if n % 10 == 3 and n != 13 else 'th'} St"
    for n in range(1, ROWS + 2)
]

# Parks as (name, col0, row0, col1, row1) in block units (inclusive-exclusive).
PARKS = [
    ("Cottonwood Commons", 1, 1, 4, 4),
    ("Bluebonnet Green", 6, 2, 9, 5),
    ("Pecan Hollow Park", 6, 7, 9, 10),
    ("Redbud Square", 11, 1, 13, 3),
    ("Limestone Terrace", 15, 2, 19, 5),
    ("Prairie Lantern Park", 1, 7, 4, 11),
    ("Heron Flats", 11, 6, 15, 10),
    ("Sycamore Landing", 16, 8, 19, 12),
    ("Juniper Steps", 2, 14, 5, 17),
    ("Mesquite Run", 7, 13, 11, 16),
    ("Bois d'Arc Meadow", 13, 14, 18, 18),
    ("Lantana Gardens", 3, 19, 8, 23),
    ("Kestrel Field", 10, 19, 13, 22),
    ("Wildrye Overlook", 15, 20, 19, 23),
]

ASSET_TYPES: dict[str, dict[str, Any]] = {
    "bench": {"prefix": "BENCH", "share": 0.20, "materials": ["steel", "wood", "recycled plastic"]},
    "trash_can": {"prefix": "TRASH", "share": 0.16, "materials": ["steel", "concrete"]},
    "light_pole": {"prefix": "LIGHT", "share": 0.14, "materials": ["aluminum", "steel"]},
    "tree": {"prefix": "TREE", "share": 0.24, "materials": ["n/a"]},
    "drinking_fountain": {"prefix": "FOUNT", "share": 0.05, "materials": ["stainless steel"]},
    "sign": {"prefix": "SIGN", "share": 0.09, "materials": ["aluminum", "wood"]},
    "picnic_table": {
        "prefix": "TABLE",
        "share": 0.08,
        "materials": ["wood", "recycled plastic", "concrete"],
    },
    "bike_rack": {"prefix": "BIKE", "share": 0.04, "materials": ["steel"]},
}
CONDITIONS = ["good", "good", "good", "fair", "fair", "poor", "damaged"]
CREWS = ["North", "Central", "South"]

# The named demo record. Baseline sits inside Pecan Hollow Park; the field report places it
# one block north, across 11th St, in a residential block.
BENCH_ID = "BENCH-0142"
BENCH_BASE = (-96.7969, 32.784340)
BENCH_PROP = (-96.79676, 32.785412)
BENCH_PROPS: dict[str, Any] = {
    "asset_id": BENCH_ID,
    "asset_type": "bench",
    "park": "Pecan Hollow Park",
    "condition": "good",
    "material": "wood",
    "install_year": 2014,
    "last_inspected": "2026-09-14",
    "notes": "Faces the north lawn.",
    "maintenance": {"crew": "Central", "contract": "PR-2025-07"},
}
BENCH_NEW_CONDITION = "damaged"

BASE_IMPORTED_AT = "2026-10-01T06:00:00Z"
PROP_IMPORTED_AT = "2026-11-01T06:00:00Z"
DEFAULT_COMPARE_FIELDS = (
    "asset_type",
    "condition",
    "install_year",
    "last_inspected",
    "material",
    "notes",
    "park",
)


def r8(x: float) -> float:
    return round(x, COORD_DECIMALS)


def block_lonlat(col: float, row: float) -> tuple[float, float]:
    return LON0 + col * DLON, LAT0 + row * DLAT


@dataclass
class Counts:
    n: int = 5000
    deletions: int = 60
    additions: int = 70
    moves: int = 120
    move_and_edit: int = 30
    edits: int = 220
    jitter: int = 900
    near_below: int = 10
    near_above: int = 10
    id_changes: int = 5
    null_to_absent: int = 8
    absent_to_null: int = 8
    number_to_string: int = 5


def _feature(lon: float, lat: float, props: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "Feature",
        "geometry": {"type": "Point", "coordinates": [r8(lon), r8(lat)]},
        "properties": props,
    }


def _random_point_in_park(
    rng: random.Random, park: tuple[str, int, int, int, int]
) -> tuple[float, float]:
    _, c0, r0, c1, r1 = park
    col = rng.uniform(c0 + 0.08, c1 - 0.08)
    row = rng.uniform(r0 + 0.1, r1 - 0.1)
    return block_lonlat(col, row)


def generate(
    counts: Counts | None = None, seed: int = SEED
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    """Return ``(baseline_fc, proposed_fc, manifest)``."""
    c = counts or Counts()
    rng = random.Random(seed)
    types = list(ASSET_TYPES)
    weights = [ASSET_TYPES[t]["share"] for t in types]
    numbering = dict.fromkeys(types, 0)

    def next_id(t: str) -> str:
        numbering[t] += 1
        n = numbering[t]
        if t == "bench" and n == 142:  # reserved for the named demo record
            numbering[t] += 1
            n = numbering[t]
        return f"{ASSET_TYPES[t]['prefix']}-{n:04d}"

    def new_asset(t: str, aid: str) -> dict[str, Any]:
        park = rng.choice(PARKS)
        lon, lat = _random_point_in_park(rng, park)
        props: dict[str, Any] = {
            "asset_id": aid,
            "asset_type": t,
            "park": park[0],
            "condition": rng.choice(CONDITIONS),
            "material": rng.choice(ASSET_TYPES[t]["materials"]),
            "install_year": rng.randint(1998, 2025),
            "last_inspected": f"2026-{rng.randint(4, 9):02d}-{rng.randint(1, 28):02d}",
            "maintenance": {
                "crew": rng.choice(CREWS),
                "contract": f"PR-20{rng.randint(22, 26)}-{rng.randint(1, 30):02d}",
            },
            "imported_at": BASE_IMPORTED_AT,
        }
        roll = rng.random()
        if roll < 0.55:
            props["notes"] = None
        elif roll < 0.8:
            props["notes"] = rng.choice(
                ["Near playground.", "Shaded.", "Close to trailhead.", "Replaced 2023."]
            )
        # else: notes absent
        return _feature(lon, lat, props)

    base: list[dict[str, Any]] = []
    bench = _feature(*BENCH_BASE, {**copy.deepcopy(BENCH_PROPS), "imported_at": BASE_IMPORTED_AT})
    base.append(bench)
    numbering["bench"] = 0
    while len(base) < c.n:
        t = rng.choices(types, weights)[0]
        base.append(new_asset(t, next_id(t)))

    by_id = {f["properties"]["asset_id"]: f for f in base}
    prop_by_id: dict[str, dict[str, Any]] = {aid: copy.deepcopy(f) for aid, f in by_id.items()}
    for f in prop_by_id.values():
        f["properties"]["imported_at"] = PROP_IMPORTED_AT

    manifest_assets: dict[str, dict[str, Any]] = {}

    def note(aid: str, status: str, **comp: Any) -> None:
        entry = manifest_assets.setdefault(
            aid, {"asset_id": aid, "status": status, "components": []}
        )
        if comp:
            entry["components"].append(comp)

    # Named demo record: move to another block + condition change.
    bp = prop_by_id[BENCH_ID]
    bp["geometry"]["coordinates"] = [r8(BENCH_PROP[0]), r8(BENCH_PROP[1])]
    bp["properties"]["condition"] = BENCH_NEW_CONDITION
    note(BENCH_ID, "modified", kind="move", intended="another block (fixed coordinates)")
    note(
        BENCH_ID,
        "modified",
        kind="attribute",
        field="condition",
        old="good",
        new=BENCH_NEW_CONDITION,
    )

    pool = [aid for aid in by_id if aid != BENCH_ID]
    rng.shuffle(pool)
    take = iter(pool)

    def pick(n: int) -> list[str]:
        return [next(take) for _ in range(n)]

    deleted = pick(c.deletions)
    for aid in deleted:
        del prop_by_id[aid]
        note(aid, "deleted", kind="deletion")

    for aid in pick(c.id_changes):
        f = prop_by_id.pop(aid)
        new_aid = aid + "A"  # re-tagged in the field
        f["properties"]["asset_id"] = new_aid
        prop_by_id[new_aid] = f
        note(aid, "deleted", kind="deletion", reason="id_changed")
        note(new_aid, "added", kind="addition", reason="id_changed")

    def move(aid: str, dist: float) -> None:
        f = prop_by_id[aid]
        lon, lat = by_id[aid]["geometry"]["coordinates"]
        az = rng.uniform(0, 360)
        nlon, nlat = offset(lon, lat, az, dist)
        f["geometry"]["coordinates"] = [r8(nlon), r8(nlat)]

    def edit(aid: str) -> None:
        f = prop_by_id[aid]["properties"]
        t = f["asset_type"]
        field = rng.choice(
            ["condition", "condition", "material", "notes", "last_inspected", "park"]
        )
        old = f.get(field)
        if field == "condition":
            new: Any = rng.choice([x for x in sorted(set(CONDITIONS)) if x != old])
        elif field == "material":
            mats = [m for m in ASSET_TYPES[t]["materials"] if m != old]
            if not mats:
                field, old, new = (
                    "condition",
                    f["condition"],
                    rng.choice([x for x in sorted(set(CONDITIONS)) if x != f["condition"]]),
                )
            else:
                new = rng.choice(mats)
        elif field == "notes":
            new = "Graffiti reported." if old != "Graffiti reported." else "Cleaned."
        elif field == "last_inspected":
            new = f"2026-10-{rng.randint(1, 28):02d}"
        else:
            new = rng.choice([p[0] for p in PARKS if p[0] != old])
        old_present = field in f
        f[field] = new
        note(
            aid,
            "modified",
            kind="attribute",
            field=field,
            old=old if old_present else None,
            old_present=old_present,
            new=new,
        )

    moved = pick(c.moves)
    for aid in moved:
        d = round(rng.lognormvariate(2.6, 0.9) + 2.5, 3)  # ~2.5 m to ~200 m
        move(aid, d)
        note(aid, "modified", kind="move", intended_distance_m=d)
    for aid in moved[: c.move_and_edit]:
        edit(aid)
    for aid in pick(c.edits):
        edit(aid)
    for aid in pick(c.near_above):
        d = round(rng.uniform(TOLERANCE_M + 0.01, TOLERANCE_M + 0.05), 4)
        move(aid, d)
        note(aid, "modified", kind="move", intended_distance_m=d, near_threshold=True)
    for aid in pick(c.near_below):
        d = round(rng.uniform(TOLERANCE_M - 0.05, TOLERANCE_M - 0.01), 4)
        move(aid, d)
        manifest_assets.setdefault(
            aid,
            {
                "asset_id": aid,
                "status": "unchanged",
                "components": [],
                "within_tolerance_m": d,
                "near_threshold": True,
            },
        )
    for aid in pick(c.jitter):
        d = round(rng.uniform(0.05, 1.5), 4)
        move(aid, d)
        manifest_assets.setdefault(
            aid, {"asset_id": aid, "status": "unchanged", "components": [], "within_tolerance_m": d}
        )
    for aid in pick(c.null_to_absent):
        f = prop_by_id[aid]["properties"]
        if "notes" in f:
            old = f.pop("notes")
            note(
                aid,
                "modified",
                kind="attribute",
                field="notes",
                old=old,
                old_present=True,
                new=None,
                new_present=False,
            )
        else:
            f["notes"] = None
            note(
                aid,
                "modified",
                kind="attribute",
                field="notes",
                old=None,
                old_present=False,
                new=None,
                new_present=True,
            )
    for aid in pick(c.absent_to_null):
        f = prop_by_id[aid]["properties"]
        if "notes" not in f:
            f["notes"] = None
            note(
                aid,
                "modified",
                kind="attribute",
                field="notes",
                old=None,
                old_present=False,
                new=None,
                new_present=True,
            )
        else:
            old = f.pop("notes")
            note(
                aid,
                "modified",
                kind="attribute",
                field="notes",
                old=old,
                old_present=True,
                new=None,
                new_present=False,
            )
    for aid in pick(c.number_to_string):
        f = prop_by_id[aid]["properties"]
        old = f["install_year"]
        f["install_year"] = str(old)
        note(
            aid,
            "modified",
            kind="attribute",
            field="install_year",
            old=old,
            new=str(old),
            type_change="number->string",
        )

    for _ in range(c.additions):
        t = rng.choices(types, weights)[0]
        aid = next_id(t)
        f = new_asset(t, aid)
        f["properties"]["imported_at"] = PROP_IMPORTED_AT
        prop_by_id[aid] = f
        note(aid, "added", kind="addition")

    # Independent ordering per version: never match by position.
    base_order = list(base)
    rng.shuffle(base_order)
    prop_order = list(prop_by_id.values())
    rng.shuffle(prop_order)

    for entry in manifest_assets.values():
        for comp in entry["components"]:
            k = comp["kind"]
            comp["id"] = f"{entry['asset_id']}:{'attr:' + comp['field'] if k == 'attribute' else k}"
    expected = sorted(
        (e for e in manifest_assets.values() if e["components"]), key=lambda e: e["asset_id"]
    )
    kinds = [cmp["kind"] for e in expected for cmp in e["components"]]
    manifest = {
        "schema": "geodiff.manifest/1",
        "note": SYNTHETIC_NOTE,
        "seed": seed,
        "tolerance_m": TOLERANCE_M,
        "compared_fields": list(DEFAULT_COMPARE_FIELDS),
        "id_field": "asset_id",
        "counts": {
            "baseline_features": len(base_order),
            "proposed_features": len(prop_order),
            "affected_assets": len(expected),
            "components": len(kinds),
            "components_by_kind": {
                k: kinds.count(k) for k in ("addition", "deletion", "move", "attribute")
            },
            "within_tolerance_moves": sum(
                1 for e in manifest_assets.values() if "within_tolerance_m" in e
            ),
        },
        "assets": expected,
        "unchanged_controls": sorted(
            e["asset_id"] for e in manifest_assets.values() if not e["components"]
        ),
    }
    meta = {"name": DEPARTMENT, "synthetic": True, "note": SYNTHETIC_NOTE, "seed": seed}
    return (
        {
            "type": "FeatureCollection",
            "name": "parks_assets_2026-10_approved",
            "geodiff:source": meta,
            "features": base_order,
        },
        {
            "type": "FeatureCollection",
            "name": "parks_assets_2026-11_field",
            "geodiff:source": meta,
            "features": prop_order,
        },
        manifest,
    )


def context_layers() -> dict[str, dict[str, Any]]:
    """Synthetic streets, blocks, parks and paths for map context."""
    inset_lon, inset_lat = 0.00012, 0.00010
    streets = []
    for i in range(COLS + 1):
        lon = LON0 + i * DLON
        streets.append(
            {
                "type": "Feature",
                "properties": {
                    "name": f"{NS_STREETS[i % len(NS_STREETS)]} Ave",
                    "class": "avenue" if i % 5 == 0 else "street",
                },
                "geometry": {
                    "type": "LineString",
                    "coordinates": [[r8(lon), r8(LAT0)], [r8(lon), r8(LAT0 + ROWS * DLAT)]],
                },
            }
        )
    for j in range(ROWS + 1):
        lat = LAT0 + j * DLAT
        streets.append(
            {
                "type": "Feature",
                "properties": {
                    "name": EW_STREETS[j],
                    "class": "avenue" if j % 6 == 0 else "street",
                },
                "geometry": {
                    "type": "LineString",
                    "coordinates": [[r8(LON0), r8(lat)], [r8(LON0 + COLS * DLON), r8(lat)]],
                },
            }
        )
    blocks = []
    for i in range(COLS):
        for j in range(ROWS):
            x0, y0 = block_lonlat(i, j)
            x1, y1 = block_lonlat(i + 1, j + 1)
            ring = [
                [x0 + inset_lon, y0 + inset_lat],
                [x1 - inset_lon, y0 + inset_lat],
                [x1 - inset_lon, y1 - inset_lat],
                [x0 + inset_lon, y1 - inset_lat],
            ]
            ring = [[r8(a), r8(b)] for a, b in ring]
            blocks.append(
                {
                    "type": "Feature",
                    "properties": {"block": f"{i}-{j}"},
                    "geometry": {"type": "Polygon", "coordinates": [[*ring, ring[0]]]},
                }
            )
    parks = []
    paths = []
    for name, c0, r0, c1, r1 in PARKS:
        x0, y0 = block_lonlat(c0, r0)
        x1, y1 = block_lonlat(c1, r1)
        ring = [
            [x0 + inset_lon, y0 + inset_lat],
            [x1 - inset_lon, y0 + inset_lat],
            [x1 - inset_lon, y1 - inset_lat],
            [x0 + inset_lon, y1 - inset_lat],
        ]
        ring = [[r8(a), r8(b)] for a, b in ring]
        parks.append(
            {
                "type": "Feature",
                "properties": {"name": name},
                "geometry": {"type": "Polygon", "coordinates": [[*ring, ring[0]]]},
            }
        )
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        loop = [
            [x0 + 3 * inset_lon, cy],
            [cx, y1 - 3 * inset_lat],
            [x1 - 3 * inset_lon, cy],
            [cx, y0 + 3 * inset_lat],
            [x0 + 3 * inset_lon, cy],
        ]
        paths.append(
            {
                "type": "Feature",
                "properties": {"park": name, "kind": "loop trail"},
                "geometry": {
                    "type": "LineString",
                    "coordinates": [[r8(a), r8(b)] for a, b in loop],
                },
            }
        )
        paths.append(
            {
                "type": "Feature",
                "properties": {"park": name, "kind": "spine"},
                "geometry": {
                    "type": "LineString",
                    "coordinates": [
                        [r8(x0 + inset_lon), r8(y0 + inset_lat)],
                        [r8(x1 - inset_lon), r8(y1 - inset_lat)],
                    ],
                },
            }
        )
    meta = {"synthetic": True, "note": SYNTHETIC_NOTE}
    return {
        "streets": {"type": "FeatureCollection", "geodiff:source": meta, "features": streets},
        "blocks": {"type": "FeatureCollection", "geodiff:source": meta, "features": blocks},
        "parks": {"type": "FeatureCollection", "geodiff:source": meta, "features": parks},
        "paths": {"type": "FeatureCollection", "geodiff:source": meta, "features": paths},
    }


def dump(obj: Any, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8"
    )


def dump_pretty(obj: Any, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
